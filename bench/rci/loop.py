"""The recursive harness-improvement loop.

    .venv/bin/python bench/rci/loop.py --iterations 3
    .venv/bin/python bench/rci/loop.py --iterations 1 --tasks 10   # cheap dry run
    .venv/bin/python bench/rci/loop.py --report-only

Each iteration:

    stack the next hypothesis onto the accepted harness
      → write bench/variant.json
      → run the dev split through Harbor
      → compare task-by-task against the incumbent (McNemar, see stats.py)
      → accept or reject, and write down why

"Recursive" is the accept step: a change that survives becomes part of the
harness the *next* hypothesis is tested against, so improvements compound
instead of each being measured against the original baseline. The accepted
stack is the harness; the ledger is its derivation.

Three properties matter more than the search being clever:

**Every run is on dev, never test.** The held-out split exists to answer "did
this actually generalize, or did I fit 45 tasks", and it can only answer that
while it stays unseen. The loop has no code path that touches it.

**A rejected result is recorded, not discarded.** Knowing that a plausible
change did nothing is most of what this loop produces; a ledger of only the
wins is a ledger that cannot be audited and will re-propose the same failures.

**The variant under test is written into every trial directory.** Months later,
a number can still be traced to the exact harness that produced it.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

BENCH = Path(__file__).resolve().parent.parent
REPO = BENCH.parent
sys.path.insert(0, str(BENCH))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from hypotheses import HYPOTHESES  # noqa: E402
from report import load_trials  # noqa: E402
from stats import compare, wilson  # noqa: E402
from variant import Variant  # noqa: E402

LEDGER = Path(__file__).resolve().parent / "ledger.jsonl"
REPORT = Path(__file__).resolve().parent / "REPORT.md"


# ── ledger ──────────────────────────────────────────────────────────────


def read_ledger() -> list[dict]:
    if not LEDGER.is_file():
        return []
    return [json.loads(line) for line in LEDGER.read_text().splitlines() if line.strip()]


def append_ledger(record: dict) -> None:
    with LEDGER.open("a") as f:
        f.write(json.dumps(record) + "\n")


def accepted_stack(ledger: list[dict]) -> Variant:
    """Rebuild the current harness by replaying every accepted change."""
    harness = Variant()
    for entry in ledger:
        if entry.get("accepted") and entry.get("variant"):
            candidate = Variant.from_dict(entry["variant"])
            harness = harness.stack(
                candidate,
                name=f"{harness.name}+{candidate.name}" if not harness.is_baseline else candidate.name,
                rationale="accepted stack",
            )
    return harness


def incumbent_outcomes(ledger: list[dict]) -> dict[str, bool] | None:
    """Per-task results of the harness currently in force."""
    for entry in reversed(ledger):
        if entry.get("accepted") or entry.get("kind") == "baseline":
            return entry.get("outcomes")
    return None


# ── running ─────────────────────────────────────────────────────────────


def run_split(variant: Variant, job_name: str, split: str, tasks: int | None, k: int) -> dict[str, bool]:
    """Stage the variant, run the split, return task → passed."""
    variant.save(BENCH)
    jobs_dir = Path(
        subprocess.run(
            ["bash", "-c", f'echo "${{KODA_BENCH_JOBS_DIR:-{REPO}/bench/jobs}}"'],
            capture_output=True, text=True, check=True,
        ).stdout.strip()
    )

    cmd = [str(BENCH / "run.sh"), split, "--job-name", job_name, "-k", str(k)]
    if tasks:
        cmd += ["-l", str(tasks)]

    print(f"\n=== running {job_name} (variant: {variant.name}) ===", flush=True)
    result = subprocess.run(cmd, cwd=REPO)
    if result.returncode != 0:
        raise RuntimeError(f"harbor run failed for {job_name} (exit {result.returncode})")

    job_dir = jobs_dir / job_name
    trials = load_trials(job_dir)
    if not trials:
        raise RuntimeError(f"no trials found in {job_dir}")
    return {t["task"]: t["reward"] >= 1.0 for t in trials}


# ── reporting ───────────────────────────────────────────────────────────


def write_report(ledger: list[dict]) -> None:
    """Render the ledger as the 'what improved what' record."""
    lines = [
        "# RCI — harness improvement log",
        "",
        "Auto-generated by `bench/rci/loop.py`. One row per hypothesis tested",
        "against the Terminal-Bench dev split. Rejections are kept: knowing a",
        "plausible change did nothing is most of what this loop produces.",
        "",
        "`fixed` / `broke` count tasks whose outcome *changed* — the only tasks",
        "carrying information about the change. `p` is an exact McNemar test on",
        "those; see `bench/rci/stats.py` for why the mean alone is not enough.",
        "",
        "| # | hypothesis | pass | fixed | broke | p | verdict |",
        "|---|---|---|---|---|---|---|",
    ]
    for i, e in enumerate(ledger):
        n, passed = e.get("n", 0), e.get("passed", 0)
        acc = f"{passed}/{n}" if n else "—"
        if e.get("kind") == "baseline":
            lines.append(f"| {i} | **baseline** | {acc} | — | — | — | reference |")
            continue
        verdict = "✅ kept" if e.get("accepted") else "❌ dropped"
        p = e.get("p_value")
        lines.append(
            f"| {i} | {e.get('name','?')} | {acc} | {len(e.get('fixed',[]))} | "
            f"{len(e.get('broke',[]))} | {p:.3f} | {verdict} |" if p is not None else
            f"| {i} | {e.get('name','?')} | {acc} | — | — | — | {verdict} |"
        )

    lines += ["", "## Detail", ""]
    for i, e in enumerate(ledger):
        lines.append(f"### {i}. {e.get('name', 'baseline')}")
        lines.append("")
        if e.get("rationale"):
            lines.append(f"**Hypothesis** — {e['rationale']}")
            lines.append("")
        if e.get("reason"):
            lines.append(f"**Verdict** — {e['reason']}")
            lines.append("")
        if e.get("fixed"):
            lines.append(f"*Fixed:* {', '.join(e['fixed'])}")
            lines.append("")
        if e.get("broke"):
            lines.append(f"*Broke:* {', '.join(e['broke'])}")
            lines.append("")
        n, passed = e.get("n", 0), e.get("passed", 0)
        if n:
            lo, hi = wilson(passed, n)
            lines.append(f"*Score:* {passed}/{n} = {passed/n:.1%} (95% CI {lo:.1%}–{hi:.1%})")
            lines.append("")

    REPORT.write_text("\n".join(lines) + "\n")
    print(f"wrote {REPORT}")


# ── main ────────────────────────────────────────────────────────────────


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--iterations", type=int, default=1)
    ap.add_argument("--split", default="dev", choices=["dev"],
                    help="dev only — the loop must never see the held-out split")
    ap.add_argument("--tasks", type=int, help="cap tasks per run (cheap dry runs)")
    ap.add_argument("-k", type=int, default=1, help="attempts per task")
    ap.add_argument("--report-only", action="store_true")
    args = ap.parse_args()

    ledger = read_ledger()
    if args.report_only:
        write_report(ledger)
        return 0

    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")

    # Baseline first — nothing can be compared without it.
    if not any(e.get("kind") == "baseline" for e in ledger):
        outcomes = run_split(Variant(), f"rci-{stamp}-baseline", args.split, args.tasks, args.k)
        append_ledger({
            "kind": "baseline",
            "name": "baseline",
            "rationale": "Unmodified harness — the number everything else is measured against.",
            "timestamp": stamp,
            "n": len(outcomes),
            "passed": sum(outcomes.values()),
            "outcomes": outcomes,
            "accepted": True,
            "variant": None,
        })
        ledger = read_ledger()

    tried = {e.get("name") for e in ledger}
    queue = [h for h in HYPOTHESES if h.name not in tried]
    if not queue:
        print("no untested hypotheses left — add more to bench/rci/hypotheses.py")
        write_report(ledger)
        return 0

    for candidate in queue[: args.iterations]:
        harness = accepted_stack(ledger)
        base = incumbent_outcomes(ledger)
        if base is None:
            print("no incumbent outcomes to compare against", file=sys.stderr)
            return 1

        stacked = harness.stack(candidate, name=candidate.name, rationale=candidate.rationale)
        job = f"rci-{stamp}-{candidate.name}"
        outcomes = run_split(stacked, job, args.split, args.tasks, args.k)
        verdict = compare(base, outcomes)

        print(f"\n{candidate.name}: {verdict.base_passed} -> {verdict.variant_passed} "
              f"({verdict.delta:+.1%})\n  {verdict.reason}")

        append_ledger({
            "kind": "experiment",
            "name": candidate.name,
            "rationale": candidate.rationale,
            "timestamp": stamp,
            "job": job,
            "n": verdict.n,
            "passed": verdict.variant_passed,
            "fixed": verdict.fixed,
            "broke": verdict.broken,
            "p_value": verdict.p_value,
            "accepted": verdict.accepted,
            "reason": verdict.reason,
            "outcomes": outcomes,
            "variant": json.loads(candidate.to_json()),
        })
        ledger = read_ledger()

    # Leave the tree holding the harness that actually won.
    accepted_stack(ledger).save(BENCH)
    write_report(ledger)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
